def text(template, language='zh', **values):
    catalog = EN if language == 'en' else ZH
    translated = catalog.get(template, template)
    if language == 'zh' and template.startswith('Use '):
        translated = '用法：' + template[4:]
    if not values:
        return translated
    values = {key: text(str(value), language) if isinstance(value, BaseException) else value
              for key, value in values.items()}
    return translated.format(**values)


def help_text(source, language='zh'):
    if language == 'zh':
        return source
    lines=[]
    for line in source.splitlines():
        match=re.match(r'^(.*?)(\s{2,})(\S.*)$',line)
        if match:
            lines.append(match[1].replace(' 或 ', ' or ')+match[2]+HELP_EN.get(match[3],match[3]))
        else:
            lines.append(HELP_EN.get(line,line))
    return '\n'.join(lines)+'\n'


